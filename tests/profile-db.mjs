import assert from 'node:assert/strict';
import { randomBytes, randomUUID } from 'node:crypto';
import express from 'express';
import pg from 'pg';
import sharp from 'sharp';
import { getPool } from '../server/database.ts';
import { migrateDatabase } from '../server/migrations.ts';
import { registerApiRoutes } from '../server/routes.ts';

if (!process.env.DATABASE_URL) throw new Error('Configure DATABASE_URL.');
const url = new URL(process.env.DATABASE_URL);
const ssl = process.env.DATABASE_SSL === 'true' || (process.env.DATABASE_SSL !== 'false' && ['require', 'verify-full'].includes(url.searchParams.get('sslmode')));
const control = new pg.Pool({ connectionString: url.toString(), ssl: ssl ? { rejectUnauthorized: false } : undefined });
const schema = `casamia_profile_test_${randomUUID().replaceAll('-', '')}`;
let server;
let created = false;
try {
  await control.query(`CREATE SCHEMA "${schema}"`);
  created = true;
  url.searchParams.set('options', `-c search_path=${schema}`);
  process.env.DATABASE_URL = url.toString();
  process.env.COOKIE_SECURE = 'false';
  await migrateDatabase();
  const app = express();
  app.use(express.json());
  registerApiRoutes(app);
  server = await new Promise(resolve => { const instance = app.listen(0, '127.0.0.1', () => resolve(instance)); });
  const base = `http://127.0.0.1:${server.address().port}`;
  let cookie = '';
  const call = async (path, method = 'GET', body, extraHeaders = {}) => {
    const response = await fetch(`${base}/api${path}`, { method, headers: { 'Content-Type': 'application/json', Cookie: cookie, ...extraHeaders }, body: body === undefined ? undefined : JSON.stringify(body) });
    const setCookie = response.headers.getSetCookie().find(value => value.startsWith('enxoval_session='));
    if (setCookie) cookie = setCookie.split(';')[0];
    return { status: response.status, cookie: setCookie, data: response.status === 204 ? null : await response.json() };
  };
  const query = async (sql, params = []) => (await getPool().query(sql, params)).rows;
  const password = randomBytes(24).toString('hex');
  const registered = await call('/auth/register','POST',{email:'profile@example.invalid',password,name:'Ana'});
  assert.equal(registered.status,201);
  const userId=registered.data.user.id;
  assert.equal((await call('/profile')).status,200,'perfil acessível sem assinatura');
  assert.equal((await call('/profile','PATCH',{name:' Ana Maria ',plan:'founder',email:'other@example.invalid'})).data.name,'Ana Maria');
  const stored=(await query('SELECT plan,email FROM users WHERE id=$1',[userId]))[0];
  assert.equal(stored.plan,'free');assert.equal(stored.email,'profile@example.invalid');
  for(const name of ['', 'X', 'x'.repeat(81)])assert.equal((await call('/profile','PATCH',{name})).status,400);
  const png=await sharp({create:{width:80,height:80,channels:3,background:'#b5532f'}}).png().toBuffer();
  const upload=await fetch(`${base}/api/profile/avatar`,{method:'POST',headers:{Cookie:cookie,'Content-Type':'image/png'},body:png});
  assert.equal(upload.status,200,await upload.clone().text());
  const uploaded=await upload.json();assert.match(uploaded.avatarUrl,/^\/api\/profile\/avatar\?v=[a-f0-9]{64}$/);
  assert.equal((await call('/bootstrap')).data.user.avatarUrl,uploaded.avatarUrl);
  const avatar=await fetch(`${base}${uploaded.avatarUrl}`,{headers:{Cookie:cookie}});
  assert.equal(avatar.status,200);assert.equal(avatar.headers.get('content-type'),'image/webp');
  assert.match(avatar.headers.get('cache-control'),/no-store/);
  const svg=await fetch(`${base}/api/profile/avatar`,{method:'POST',headers:{Cookie:cookie,'Content-Type':'image/svg+xml'},body:'<svg xmlns="http://www.w3.org/2000/svg" width="80" height="80"></svg>'});
  assert.equal(svg.status,415,'rejeita SVG');
  const firstCookie=cookie;
  const other=await call('/auth/register','POST',{email:'other@example.invalid',password});
  assert.equal(other.status,201);
  assert.equal((await fetch(`${base}${uploaded.avatarUrl}`,{headers:{Cookie:cookie}})).status,404,'a foto é vinculada à sessão do próprio usuário');
  assert.equal((await fetch(`${base}${uploaded.avatarUrl}`)).status,401);
  const otherCookie=cookie;cookie=firstCookie;
  assert.equal((await call('/profile/avatar','DELETE')).data.avatarUrl,null);
  assert.equal((await fetch(`${base}${uploaded.avatarUrl}`,{headers:{Cookie:cookie}})).status,404);
  await query("UPDATE users SET plan='monthly' WHERE id=$1",[userId]);
  const home=await call('/enxovais','POST',{name:'Casa',useDefaultTemplate:false});
  assert.equal(home.status,201);
  const homeId=home.data.enxoval.id;
  assert.equal((await call(`/enxovais/${homeId}`,'PATCH',{name:'Meu novo lar',moveDate:'2027-03-01',state:'BA',city:'salvador',spendingTier:'economico'})).status,200);
  const saved=(await query('SELECT name,move_date,state,city,spending_tier FROM enxovais WHERE id=$1',[homeId]))[0];
  assert.equal(saved.name,'Meu novo lar');assert.equal(saved.city,'salvador');assert.equal(saved.spending_tier,'economico');
  cookie=otherCookie;
  assert.equal((await call(`/enxovais/${homeId}`,'PATCH',{name:'Indevido'})).status,404);
  cookie=firstCookie;
  await call('/auth/logout','POST',{});
  assert.equal((await call('/profile')).status,401);
  console.log('PASS: profile editing, avatar upload/removal and isolation, no plan escalation, home editing restricted to owner.');
} finally {
  if (server) await new Promise((resolve,reject)=>server.close(error=>error?reject(error):resolve()));
  await getPool().end();
  if(created)await control.query(`DROP SCHEMA "${schema}" CASCADE`);
  await control.end();
}
